/*
    MapPLUTO Raw Data QC
    =====================

    Source:
        data/raw/nyc_mappluto_22v3_shp/MapPLUTO.shp

    Import method:
        QGIS → PostgreSQL → schema: raw → table: mappluto

    The raw table is created by QGIS during the import.
    This script does NOT create or modify raw.mappluto.

    Source geometry:
        MultiPolygon
        EPSG:2263

    Raw-data principle:
        The raw layer preserves the source data as imported.
        Source anomalies are documented rather than silently
        corrected or deleted.

    Important:
        The "id" column that appeared during the QGIS import was
        generated by the import process and was removed because
        it is not part of the source MapPLUTO dataset.
*/


/* ============================================================
   1. STRUCTURAL QC
   ============================================================ */


/*
    1.1 Row count

    Expected:
        856,997
*/

SELECT
    COUNT(*) AS row_count
FROM raw.mappluto;


/*
    1.2 Column structure

    Used to verify that the imported table contains the expected
    MapPLUTO source fields and data types.
*/

SELECT
    column_name,
    data_type,
    udt_name
FROM information_schema.columns
WHERE table_schema = 'raw'
  AND table_name = 'mappluto'
ORDER BY ordinal_position;


/* ============================================================
   2. GEOMETRY QC
   ============================================================ */


/*
    2.1 Geometry type and CRS

    Expected:
        ST_MultiPolygon
        EPSG:2263
*/

SELECT
    ST_GeometryType(geom) AS geometry_type,
    ST_SRID(geom) AS srid,
    COUNT(*) AS feature_count
FROM raw.mappluto
GROUP BY
    ST_GeometryType(geom),
    ST_SRID(geom);


/*
    2.2 Geometry validity

    Expected:
        null_geometry   = 0
        empty_geometry  = 0
        invalid_geometry = 0
*/

SELECT
    COUNT(*) AS total_features,

    COUNT(*) FILTER (
        WHERE geom IS NULL
    ) AS null_geometry,

    COUNT(*) FILTER (
        WHERE ST_IsEmpty(geom)
    ) AS empty_geometry,

    COUNT(*) FILTER (
        WHERE NOT ST_IsValid(geom)
    ) AS invalid_geometry

FROM raw.mappluto;


/*
    2.3 Spatial extent

    Expected approximately:

        min_x = 913128.93
        min_y = 120048.99
        max_x = 1067335.95
        max_y = 272811.18
*/

SELECT
    ST_XMin(extent) AS min_x,
    ST_YMin(extent) AS min_y,
    ST_XMax(extent) AS max_x,
    ST_YMax(extent) AS max_y
FROM (
    SELECT ST_Extent(geom) AS extent
    FROM raw.mappluto
) AS e;


/* ============================================================
   3. IDENTIFIER QC
   ============================================================ */


/*
    3.1 BBL completeness and uniqueness

    Expected:

        total_rows   = 856,997
        non_null_bbl = 856,997
        distinct_bbl = 856,997

    BBL is used as the primary parcel identifier in the
    analytical workflow.
*/

SELECT
    COUNT(*) AS total_rows,
    COUNT("BBL") AS non_null_bbl,
    COUNT(DISTINCT "BBL") AS distinct_bbl
FROM raw.mappluto;


